const cache = new Map<string, HTMLCanvasElement>();
/** 渲染像素图标（带 1px 透明边距） */
export function getIcon(name: string): HTMLCanvasElement {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = ICONS[name] ?? ICONS.help;
  const size = 16;
  const cv = document.createElement('canvas');
  cv.width = size; cv.height = size;
  const ctx = cv.getContext('2d')!;
  rows.forEach((row, y) => {
    for (let x = 0; x < Math.min(row.length, size - 2); x++) {
      const c = COLORS[row[x]];
      if (c) {
        ctx.fillStyle = c;
        ctx.fillRect(x + 1, y + 1, 1, 1);
      }
    }
  });
  cache.set(name, cv);
  return cv;
}

/** 图标 dataURL（用于 <img>） */
export function iconURI(name: string): string {
  return getIcon(name).toDataURL('image/png');
}
